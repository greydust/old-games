def export_quests(dialogues):
    result = []
    evidence = []
    for name, objective, reward, ranges in QUESTS:
        ids = list(dict.fromkeys(i for a, b in ranges for i in range(a, b)))
        result.append(dict(name=name, objective=objective, reward=reward,
                           trigger=TRIGGERS.get(name, '觸發條件待確認'),
                           dialogue=[dialogues[i] for i in ids]))
        evidence.append(dict(name=name, records=ids))
    return result, evidence
